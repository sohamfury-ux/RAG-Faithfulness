def main():
    path = ROOT / "data" / "evalset.jsonl"
    existing = [json.loads(l) for l in open(path, encoding="utf-8") if l.strip()]
    kept = [e for e in existing if e.get("split") != "test"]       # idempotent re-run
    new = []
    for n, (typ, q, gold, acc, ev, ev2, notes) in enumerate(ITEMS, 1):
        row = {"id": f"t{n:03d}", "type": typ, "question": q, "gold": gold, "acceptable": acc,
               "evidence": ev, "seen": False, "notes": notes, "status": "draft", "split": "test"}
        if ev2:
            row["evidence2"] = ev2
        new.append(row)
    with open(path, "w", encoding="utf-8") as f:
        for r in kept + new:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"dev={len(kept)} test={len(new)} total={len(kept) + len(new)}")


if __name__ == "__main__":
    main()
